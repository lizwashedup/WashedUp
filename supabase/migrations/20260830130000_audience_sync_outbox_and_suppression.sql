$function$;

CREATE OR REPLACE FUNCTION public.purge_audience_personal_data(p_batch_size integer DEFAULT 1000)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE v_limit integer; v_deleted integer := 0; v_rows integer;
BEGIN
  IF p_batch_size IS NULL OR p_batch_size < 1 OR p_batch_size > 10000 THEN
    RAISE EXCEPTION 'audience retention batch size must be between 1 and 10000';
  END IF;
  v_limit := p_batch_size;
  WITH doomed AS (
    SELECT id FROM public.audience_sync_outbox
     WHERE purge_after < now() ORDER BY id LIMIT v_limit
  ) DELETE FROM public.audience_sync_outbox o USING doomed d WHERE o.id = d.id;
  GET DIAGNOSTICS v_rows = ROW_COUNT; v_deleted := v_deleted + v_rows;
  WITH doomed AS (
    SELECT id FROM public.audience_contact_reconciliation
     WHERE purge_after < now() ORDER BY id LIMIT greatest(v_limit - v_deleted, 0)
  ) DELETE FROM public.audience_contact_reconciliation r USING doomed d WHERE r.id = d.id;
  GET DIAGNOSTICS v_rows = ROW_COUNT; v_deleted := v_deleted + v_rows;
  DELETE FROM public.audience_webhook_quarantine
   WHERE provider_event_id IN (
     SELECT provider_event_id FROM public.audience_webhook_quarantine
      WHERE expires_at < now() ORDER BY received_at LIMIT greatest(v_limit - v_deleted, 0)
   );
  GET DIAGNOSTICS v_rows = ROW_COUNT; v_deleted := v_deleted + v_rows;
  DELETE FROM public.audience_consent_events
   WHERE id IN (
     SELECT id FROM public.audience_consent_events
      WHERE occurred_at < now() - interval '2 years'
      ORDER BY id LIMIT greatest(v_limit - v_deleted, 0)
   );
  GET DIAGNOSTICS v_rows = ROW_COUNT; v_deleted := v_deleted + v_rows;
  DELETE FROM public.audience_suppression_events
   WHERE provider_event_id IN (
     SELECT provider_event_id FROM public.audience_suppression_events
      WHERE received_at < now() - interval '2 years'
      ORDER BY received_at LIMIT greatest(v_limit - v_deleted, 0)
   );
  GET DIAGNOSTICS v_rows = ROW_COUNT; v_deleted := v_deleted + v_rows;
  RETURN v_deleted;
END;
$function$;

