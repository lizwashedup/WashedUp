-- Ordinary contact.updated events are reversible preferences and must be
-- reconciled against current provider state. They never enter this hard block.
CREATE OR REPLACE FUNCTION public.record_audience_suppression(
  p_provider_event_id text,
  p_event_type text,
  p_email text
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_email text := public.audience_normalize_email(p_email);
  v_inserted boolean;
BEGIN
  IF p_event_type NOT IN ('email.bounced', 'email.complained', 'email.suppressed') THEN
    RAISE EXCEPTION 'event is not a hard suppression' USING ERRCODE = '22023';
  END IF;
  IF nullif(btrim(p_provider_event_id), '') IS NULL OR v_email IS NULL THEN
    RAISE EXCEPTION 'provider event id and email are required' USING ERRCODE = '22023';
  END IF;
  INSERT INTO public.audience_suppression_events(provider_event_id, event_type, email_hash)
  VALUES (p_provider_event_id, p_event_type, encode(digest(v_email, 'sha256'), 'hex'))
  ON CONFLICT (provider_event_id) DO NOTHING;
  v_inserted := FOUND;
  IF v_inserted THEN
    UPDATE public.profiles
       SET marketing_opt_in = false,
           marketing_opt_in_source = 'provider_hard_suppression'
     WHERE public.audience_normalize_email(email) = v_email
       AND marketing_opt_in IS DISTINCT FROM false;
    PERFORM public.enqueue_audience_sync_for_email(v_email, false);
  END IF;
  RETURN v_inserted;
END;
$function$;

CREATE OR REPLACE FUNCTION public.quarantine_audience_webhook(
  p_provider_event_id text,
  p_event_type text,
  p_email text,
  p_reason text,
  p_provider_message_id text DEFAULT NULL,
  p_application_tag text DEFAULT NULL,
  p_hard_eligible boolean DEFAULT false
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE v_email text := public.audience_normalize_email(p_email);
BEGIN
  INSERT INTO public.audience_webhook_quarantine(
    provider_event_id, event_type, email_hash, reason,
    provider_message_id, application_tag, hard_eligible
  ) VALUES (
    p_provider_event_id, p_event_type,
    CASE WHEN v_email IS NULL THEN NULL ELSE encode(digest(v_email, 'sha256'), 'hex') END,
    left(coalesce(nullif(btrim(p_reason), ''), 'unscoped provider event'), 300),
    nullif(btrim(p_provider_message_id), ''), nullif(btrim(p_application_tag), ''),
    coalesce(p_hard_eligible, false)
  ) ON CONFLICT (provider_event_id) DO NOTHING;
  RETURN 'quarantined';
END;
$function$;

CREATE OR REPLACE FUNCTION public.record_audience_provider_event(
  p_provider_event_id text,
  p_event_type text,
  p_email text,
  p_provider_contact_id text DEFAULT NULL,
  p_audience_id text DEFAULT NULL,
  p_expected_audience_id text DEFAULT NULL,
  p_provider_message_id text DEFAULT NULL,
  p_application_tag text DEFAULT NULL,
  p_permanent_bounce boolean DEFAULT false
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_email text := public.audience_normalize_email(p_email);
  v_profile public.profiles%ROWTYPE;
  v_message_owned boolean := false;
  v_mode text;
  v_profile_count integer;
BEGIN
  IF nullif(btrim(p_provider_event_id), '') IS NULL OR v_email IS NULL THEN
    RAISE EXCEPTION 'provider event id and email are required' USING ERRCODE = '22023';
  END IF;
  IF EXISTS (SELECT 1 FROM public.audience_webhook_quarantine WHERE provider_event_id = p_provider_event_id)
     OR EXISTS (SELECT 1 FROM public.audience_suppression_events WHERE provider_event_id = p_provider_event_id)
     OR EXISTS (SELECT 1 FROM public.audience_contact_reconciliation WHERE provider_event_id = p_provider_event_id) THEN
    RETURN 'duplicate';
  END IF;
  SELECT activation_mode INTO v_mode FROM public.delivery_runtime_config WHERE singleton;
  IF v_mode IS NULL THEN v_mode := 'quarantined'; END IF;

  IF p_event_type = 'contact.updated' THEN
    IF nullif(btrim(p_provider_contact_id), '') IS NULL
       OR nullif(btrim(p_expected_audience_id), '') IS NULL
       OR p_audience_id IS DISTINCT FROM p_expected_audience_id THEN
      RETURN public.quarantine_audience_webhook(
        p_provider_event_id, p_event_type, v_email, 'contact is not scoped to the configured WashedUp audience'
      );
    END IF;
    SELECT * INTO v_profile FROM public.profiles
     WHERE public.audience_normalize_email(email) = v_email;
    IF NOT FOUND THEN
      RETURN public.quarantine_audience_webhook(
        p_provider_event_id, p_event_type, v_email, 'contact does not resolve to one WashedUp profile'
      );
    END IF;
    IF EXISTS (
      SELECT 1 FROM public.profiles p
       WHERE public.audience_normalize_email(p.email) = v_email AND p.id <> v_profile.id
    ) THEN
      RETURN public.quarantine_audience_webhook(
        p_provider_event_id, p_event_type, v_email, 'contact resolves to multiple WashedUp profiles'
      );
    END IF;
    INSERT INTO public.audience_contact_reconciliation(
      provider_event_id, profile_id, normalized_email, email_hash,
      provider_contact_id, expected_audience_id, local_consent_revision
    ) VALUES (
      p_provider_event_id, v_profile.id, v_email, encode(digest(v_email, 'sha256'), 'hex'),
      p_provider_contact_id, p_expected_audience_id, v_profile.marketing_consent_revision
    );
    RETURN 'reconciliation_queued';
  END IF;

  IF p_event_type NOT IN ('email.bounced', 'email.complained', 'email.suppressed') THEN
    RETURN public.quarantine_audience_webhook(
      p_provider_event_id, p_event_type, v_email, 'unsupported provider event type'
    );
  END IF;
  IF p_event_type = 'email.bounced' AND NOT p_permanent_bounce THEN
    RETURN public.quarantine_audience_webhook(
      p_provider_event_id, p_event_type, v_email, 'bounce was not classified permanent',
      p_provider_message_id, p_application_tag, false
    );
  END IF;

  SELECT EXISTS (
    SELECT 1 FROM public.transactional_email_jobs
     WHERE provider_message_id = nullif(btrim(p_provider_message_id), '')
  ) INTO v_message_owned;
  IF NOT v_message_owned
     AND EXISTS (
       SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'ticket_orders'
          AND column_name = 'confirmation_email_id'
     )
     AND nullif(btrim(p_provider_message_id), '') IS NOT NULL THEN
    EXECUTE 'select exists (select 1 from public.ticket_orders where confirmation_email_id = $1)'
      INTO v_message_owned USING p_provider_message_id;
  END IF;
  IF NOT v_message_owned AND p_application_tag IS DISTINCT FROM 'washedup' THEN
    RETURN public.quarantine_audience_webhook(
      p_provider_event_id, p_event_type, v_email,
      'email event has no WashedUp send receipt or application tag',
      p_provider_message_id, p_application_tag,
      p_event_type IN ('email.complained', 'email.suppressed')
        OR (p_event_type = 'email.bounced' AND p_permanent_bounce)
    );
  END IF;
  SELECT count(*) INTO v_profile_count FROM public.profiles p
   WHERE public.audience_normalize_email(p.email) = v_email;
  IF v_mode = 'quarantined'
     OR (v_mode = 'seed_only' AND (
       v_profile_count <> 1 OR NOT EXISTS (
         SELECT 1 FROM public.delivery_seed_profiles s
          JOIN public.profiles p ON p.id = s.profile_id
         WHERE public.audience_normalize_email(p.email) = v_email
       )
     )) THEN
    RETURN public.quarantine_audience_webhook(
      p_provider_event_id, p_event_type, v_email,
      'provider event is outside the current delivery activation scope',
      p_provider_message_id, p_application_tag, true
    );
  END IF;
  PERFORM public.record_audience_suppression(p_provider_event_id, p_event_type, v_email);
  RETURN 'hard_suppression_recorded';
END;
$function$;

CREATE OR REPLACE FUNCTION public.reconcile_quarantined_audience_events(
  p_batch_size integer DEFAULT 10
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_limit integer := least(greatest(coalesce(p_batch_size, 10), 1), 50);
  v_mode text;
  v_row public.audience_webhook_quarantine%ROWTYPE;
  v_profile public.profiles%ROWTYPE;
  v_profile_count integer;
  v_owned boolean;
  v_resolved integer := 0;
BEGIN
  SELECT activation_mode INTO v_mode FROM public.delivery_runtime_config WHERE singleton;
  IF v_mode IS NULL OR v_mode = 'quarantined' THEN RETURN 0; END IF;
  FOR v_row IN
    SELECT * FROM public.audience_webhook_quarantine
     WHERE status = 'pending' AND available_at <= now()
       AND hard_eligible
       AND event_type IN ('email.bounced', 'email.complained', 'email.suppressed')
     ORDER BY received_at LIMIT v_limit FOR UPDATE SKIP LOCKED
  LOOP
    v_owned := coalesce(v_row.application_tag = 'washedup', false);
    IF NOT v_owned AND v_row.provider_message_id IS NOT NULL THEN
      SELECT EXISTS (
        SELECT 1 FROM public.transactional_email_jobs
         WHERE provider_message_id = v_row.provider_message_id
      ) INTO v_owned;
      IF NOT v_owned AND EXISTS (
        SELECT 1 FROM information_schema.columns
         WHERE table_schema = 'public' AND table_name = 'ticket_orders'
           AND column_name = 'confirmation_email_id'
      ) THEN
        EXECUTE 'select exists (select 1 from public.ticket_orders where confirmation_email_id = $1)'
          INTO v_owned USING v_row.provider_message_id;
      END IF;
    END IF;
    SELECT count(*) INTO v_profile_count FROM public.profiles p
     WHERE encode(digest(public.audience_normalize_email(p.email), 'sha256'), 'hex') = v_row.email_hash;
    SELECT * INTO v_profile FROM public.profiles p
     WHERE encode(digest(public.audience_normalize_email(p.email), 'sha256'), 'hex') = v_row.email_hash
     ORDER BY p.id LIMIT 1;
    IF v_owned AND v_profile_count = 1 AND v_profile.id IS NOT NULL
       AND (v_mode = 'live' OR EXISTS (
         SELECT 1 FROM public.delivery_seed_profiles s WHERE s.profile_id = v_profile.id
       )) THEN
      PERFORM public.record_audience_suppression(
        v_row.provider_event_id, v_row.event_type, v_profile.email
      );
      UPDATE public.audience_webhook_quarantine
         SET status = 'resolved', last_checked_at = now(), reason = 'WashedUp send receipt reconciled'
       WHERE provider_event_id = v_row.provider_event_id;
      v_resolved := v_resolved + 1;
    ELSE
      UPDATE public.audience_webhook_quarantine
         SET attempts = attempts + 1,
             last_checked_at = now(),
             available_at = now() + interval '1 hour',
             status = CASE WHEN expires_at <= now() THEN 'expired' ELSE status END
       WHERE provider_event_id = v_row.provider_event_id;
    END IF;
  END LOOP;
  RETURN v_resolved;
END;
$function$;

CREATE OR REPLACE FUNCTION public.claim_audience_contact_reconciliations(
  p_batch_size integer DEFAULT 10,
  p_lease_seconds integer DEFAULT 600
)
RETURNS SETOF public.audience_contact_reconciliation
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_limit integer := least(greatest(coalesce(p_batch_size, 10), 1), 10);
  v_lease integer := least(greatest(coalesce(p_lease_seconds, 600), 300), 3600);
  v_mode text;
BEGIN
  SELECT activation_mode INTO v_mode FROM public.delivery_runtime_config WHERE singleton;
  IF v_mode IS NULL OR v_mode = 'quarantined' THEN RETURN; END IF;
  RETURN QUERY
  WITH chosen AS (
    SELECT r.id FROM public.audience_contact_reconciliation r
     WHERE ((r.status = 'pending' AND r.available_at <= now())
         OR (r.status = 'processing' AND r.claimed_at < now() - make_interval(secs => v_lease)))
       AND (v_mode = 'live' OR EXISTS (
         SELECT 1 FROM public.delivery_seed_profiles s WHERE s.profile_id = r.profile_id
       ))
     ORDER BY r.available_at, r.id
     LIMIT v_limit FOR UPDATE SKIP LOCKED
  )
  UPDATE public.audience_contact_reconciliation r
     SET status = 'processing', attempts = r.attempts + 1,
         claimed_at = now(), updated_at = now()
    FROM chosen c WHERE r.id = c.id
  RETURNING r.*;
END;
$function$;

CREATE OR REPLACE FUNCTION public.complete_audience_contact_reconciliation(
  p_id bigint,
  p_provider_unsubscribed boolean,
  p_confirmed_audience_id text,
  p_confirmed boolean DEFAULT false,
  p_error text DEFAULT NULL
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_job public.audience_contact_reconciliation%ROWTYPE;
  v_current_revision bigint;
BEGIN
  SELECT * INTO v_job FROM public.audience_contact_reconciliation WHERE id = p_id FOR UPDATE;
  IF NOT FOUND OR v_job.status <> 'processing' THEN RETURN false; END IF;
  IF NOT p_confirmed OR p_confirmed_audience_id IS DISTINCT FROM v_job.expected_audience_id THEN
    UPDATE public.audience_contact_reconciliation
       SET status = 'pending', claimed_at = NULL,
           available_at = now() + interval '5 minutes',
           last_error = left(coalesce(p_error, 'provider state was not confirmed'), 500), updated_at = now()
     WHERE id = p_id;
    RETURN false;
  END IF;
  SELECT marketing_consent_revision INTO v_current_revision
    FROM public.profiles WHERE id = v_job.profile_id FOR UPDATE;
  IF v_current_revision IS DISTINCT FROM v_job.local_consent_revision
     OR EXISTS (
       SELECT 1 FROM public.audience_sync_outbox o
        WHERE o.profile_id = v_job.profile_id
          AND o.revision > v_job.local_consent_revision
          AND o.status IN ('pending', 'processing')
     ) THEN
    UPDATE public.audience_contact_reconciliation
       SET status = 'cancelled', claimed_at = NULL, terminal_at = now(),
           purge_after = now() + interval '30 days',
           last_error = 'stale provider preference ignored after newer local consent', updated_at = now()
     WHERE id = p_id;
    RETURN false;
  END IF;

  INSERT INTO public.audience_provider_preferences(
    profile_id, email_hash, unsubscribed, local_consent_revision,
    provider_event_id, confirmed_at
  ) VALUES (
    v_job.profile_id, v_job.email_hash, p_provider_unsubscribed,
    v_job.local_consent_revision, v_job.provider_event_id, now()
  ) ON CONFLICT (profile_id) DO UPDATE
    SET email_hash = EXCLUDED.email_hash,
        unsubscribed = EXCLUDED.unsubscribed,
        local_consent_revision = EXCLUDED.local_consent_revision,
        provider_event_id = EXCLUDED.provider_event_id,
        confirmed_at = now();

  IF p_provider_unsubscribed THEN
    UPDATE public.profiles
       SET marketing_opt_in = false,
           marketing_opt_in_source = 'provider_preference'
     WHERE id = v_job.profile_id
       AND marketing_consent_revision = v_job.local_consent_revision
       AND marketing_opt_in IS DISTINCT FROM false;
  END IF;
  UPDATE public.audience_contact_reconciliation
     SET status = 'delivered', claimed_at = NULL, terminal_at = now(),
         purge_after = now() + interval '30 days', last_error = NULL, updated_at = now()
   WHERE id = p_id;
  RETURN true;
END;
$function$;

-- Replace the original claim with activation and seed scoping.
CREATE OR REPLACE FUNCTION public.claim_audience_sync_jobs(
  p_batch_size integer DEFAULT 10,
  p_lease_seconds integer DEFAULT 600
)
RETURNS SETOF public.audience_sync_outbox
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_limit integer := least(greatest(coalesce(p_batch_size, 10), 1), 10);
  v_lease integer := least(greatest(coalesce(p_lease_seconds, 600), 300), 3600);
  v_mode text;
BEGIN
  SELECT activation_mode INTO v_mode FROM public.delivery_runtime_config WHERE singleton;
  IF v_mode IS NULL OR v_mode = 'quarantined' THEN RETURN; END IF;
  RETURN QUERY
  WITH chosen AS (
    SELECT o.id FROM public.audience_sync_outbox o
    WHERE ((o.status = 'pending' AND o.available_at <= now())
       OR (o.status = 'processing' AND o.claimed_at < now() - make_interval(secs => v_lease)))
      AND (
        v_mode = 'live'
