CREATE OR REPLACE FUNCTION public.enqueue_audience_sync_for_email(
  p_email text,
  p_marketing_opt_in boolean
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_email text := public.audience_normalize_email(p_email);
  v_desired boolean := coalesce(p_marketing_opt_in, false);
BEGIN
  IF v_email IS NULL THEN RETURN; END IF;
  IF EXISTS (
    SELECT 1 FROM public.audience_suppression_events
     WHERE email_hash = encode(digest(v_email, 'sha256'), 'hex')
  ) THEN
    v_desired := false;
  END IF;
  INSERT INTO public.audience_sync_outbox
    (normalized_email, desired_marketing_opt_in, status, available_at, updated_at)
  VALUES (v_email, v_desired, 'pending', now(), now())
  ON CONFLICT (normalized_email) DO UPDATE
    SET desired_marketing_opt_in = EXCLUDED.desired_marketing_opt_in,
        revision = public.audience_sync_outbox.revision +
          CASE WHEN public.audience_sync_outbox.desired_marketing_opt_in
                    IS DISTINCT FROM EXCLUDED.desired_marketing_opt_in
                    OR public.audience_sync_outbox.status IN ('failed', 'cancelled')
               THEN 1 ELSE 0 END,
        status = CASE
          WHEN public.audience_sync_outbox.desired_marketing_opt_in
                 IS DISTINCT FROM EXCLUDED.desired_marketing_opt_in
               AND public.audience_sync_outbox.status = 'processing'
            THEN 'processing'
          WHEN public.audience_sync_outbox.desired_marketing_opt_in
                 IS DISTINCT FROM EXCLUDED.desired_marketing_opt_in
               OR public.audience_sync_outbox.status IN ('failed', 'cancelled')
            THEN 'pending'
          ELSE public.audience_sync_outbox.status END,
        attempts = CASE WHEN
          (public.audience_sync_outbox.desired_marketing_opt_in
             IS DISTINCT FROM EXCLUDED.desired_marketing_opt_in
           AND public.audience_sync_outbox.status <> 'processing')
          OR public.audience_sync_outbox.status IN ('failed', 'cancelled')
          THEN 0 ELSE public.audience_sync_outbox.attempts END,
        available_at = CASE WHEN
          (public.audience_sync_outbox.desired_marketing_opt_in
             IS DISTINCT FROM EXCLUDED.desired_marketing_opt_in
           AND public.audience_sync_outbox.status <> 'processing')
          OR public.audience_sync_outbox.status IN ('failed', 'cancelled')
          THEN now() ELSE public.audience_sync_outbox.available_at END,
        claimed_at = CASE WHEN
          (public.audience_sync_outbox.desired_marketing_opt_in
             IS DISTINCT FROM EXCLUDED.desired_marketing_opt_in
           AND public.audience_sync_outbox.status <> 'processing')
          OR public.audience_sync_outbox.status IN ('failed', 'cancelled')
          THEN NULL ELSE public.audience_sync_outbox.claimed_at END,
        delivered_at = CASE WHEN
          (public.audience_sync_outbox.desired_marketing_opt_in
             IS DISTINCT FROM EXCLUDED.desired_marketing_opt_in
           AND public.audience_sync_outbox.status <> 'processing')
          OR public.audience_sync_outbox.status IN ('failed', 'cancelled')
          THEN NULL ELSE public.audience_sync_outbox.delivered_at END,
        last_error = CASE WHEN
          (public.audience_sync_outbox.desired_marketing_opt_in
             IS DISTINCT FROM EXCLUDED.desired_marketing_opt_in
           AND public.audience_sync_outbox.status <> 'processing')
          OR public.audience_sync_outbox.status IN ('failed', 'cancelled')
          THEN NULL ELSE public.audience_sync_outbox.last_error END,
        updated_at = now();
END;
$function$;

CREATE OR REPLACE FUNCTION public.record_profile_consent_evidence()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_changed boolean;
  v_source text;
  v_suppressed boolean := false;
BEGIN
  IF public.audience_normalize_email(NEW.email) IS NOT NULL THEN
    SELECT EXISTS (
      SELECT 1 FROM public.audience_suppression_events
       WHERE email_hash = encode(digest(public.audience_normalize_email(NEW.email), 'sha256'), 'hex')
    ) INTO v_suppressed;
  END IF;
  IF v_suppressed AND coalesce(NEW.marketing_opt_in, false) THEN
    NEW.marketing_opt_in := false;
  END IF;
  IF TG_OP = 'INSERT' THEN
    v_changed := true;
  ELSE
    v_changed := OLD.email IS DISTINCT FROM NEW.email
      OR OLD.marketing_opt_in IS DISTINCT FROM NEW.marketing_opt_in;
  END IF;
  IF NOT v_changed THEN
    NEW.marketing_opt_in_source := OLD.marketing_opt_in_source;
    RETURN NEW;
  END IF;
  v_source := CASE
    WHEN v_suppressed THEN 'provider_suppression'
    WHEN TG_OP = 'INSERT' THEN 'profile_insert'
    ELSE 'profile_change'
  END;
  NEW.marketing_opt_in_source := v_source;
  IF TG_OP = 'INSERT' THEN
    NEW.marketing_opt_in_at := now();
  ELSIF OLD.marketing_opt_in IS DISTINCT FROM NEW.marketing_opt_in THEN
    NEW.marketing_opt_in_at := now();
  END IF;
  INSERT INTO public.audience_consent_events
    (profile_id, email_hash, email_consent, marketing_opt_in, consent_source)
  VALUES (NEW.id, encode(digest(public.audience_normalize_email(NEW.email), 'sha256'), 'hex'), NEW.email IS NOT NULL,
          coalesce(NEW.marketing_opt_in, false), v_source);
  IF TG_OP = 'UPDATE' THEN
    IF OLD.email IS DISTINCT FROM NEW.email THEN
      PERFORM public.enqueue_audience_sync_for_email(OLD.email, false);
    END IF;
  END IF;
  PERFORM public.enqueue_audience_sync_for_email(NEW.email, coalesce(NEW.marketing_opt_in, false));
  RETURN NEW;
END;
$function$;

DROP TRIGGER IF EXISTS profile_consent_evidence_trigger ON public.profiles;
CREATE TRIGGER profile_consent_evidence_trigger
BEFORE INSERT OR UPDATE OF email, marketing_opt_in, marketing_opt_in_source
ON public.profiles FOR EACH ROW EXECUTE FUNCTION public.record_profile_consent_evidence();

CREATE OR REPLACE FUNCTION public.record_audience_suppression(
  p_provider_event_id text,
  p_event_type text,
  p_email text
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_email text := public.audience_normalize_email(p_email);
  v_hash text;
  v_inserted boolean;
BEGIN
  IF nullif(btrim(p_provider_event_id), '') IS NULL OR v_email IS NULL THEN
    RAISE EXCEPTION 'provider event id and email are required' USING ERRCODE = '22023';
  END IF;
  v_hash := encode(digest(v_email, 'sha256'), 'hex');
  INSERT INTO public.audience_suppression_events(provider_event_id, event_type, email_hash)
  VALUES (p_provider_event_id, p_event_type, v_hash)
  ON CONFLICT (provider_event_id) DO NOTHING;
  v_inserted := FOUND;
  IF v_inserted THEN
    PERFORM public.enqueue_audience_sync_for_email(v_email, false);
    UPDATE public.profiles
       SET marketing_opt_in = false,
           marketing_opt_in_source = 'provider_suppression'
     WHERE public.audience_normalize_email(email) = v_email
       AND marketing_opt_in IS DISTINCT FROM false;
  END IF;
  RETURN v_inserted;
END;
$function$;

CREATE OR REPLACE FUNCTION public.enqueue_current_profile_audience_sync(p_profile_id uuid)
