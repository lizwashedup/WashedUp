CREATE OR REPLACE FUNCTION public.profile_consent_evidence_enqueue()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_changed boolean;
  v_email text := public.audience_normalize_email(NEW.email);
BEGIN
  IF TG_OP = 'INSERT' THEN
    v_changed := true;
  ELSE
    v_changed := OLD.email IS DISTINCT FROM NEW.email
      OR OLD.marketing_opt_in IS DISTINCT FROM NEW.marketing_opt_in;
  END IF;
  IF NOT v_changed THEN RETURN NEW; END IF;

  INSERT INTO public.audience_consent_events(
    profile_id, email_hash, email_consent, marketing_opt_in,
    consent_source, consent_revision
  ) VALUES (
    NEW.id,
    CASE WHEN v_email IS NULL THEN NULL ELSE encode(digest(v_email, 'sha256'), 'hex') END,
    v_email IS NOT NULL,
    coalesce(NEW.marketing_opt_in, false),
    NEW.marketing_opt_in_source,
    NEW.marketing_consent_revision
  );

  IF TG_OP = 'UPDATE' AND OLD.email IS DISTINCT FROM NEW.email THEN
    PERFORM public.enqueue_audience_sync_for_email(OLD.email, false);
  END IF;
  PERFORM public.enqueue_audience_sync_for_profile(
    NEW.id, NEW.email, coalesce(NEW.marketing_opt_in, false)
  );

  IF coalesce(NEW.marketing_opt_in, false) THEN
    UPDATE public.audience_provider_preferences
       SET unsubscribed = false,
           local_consent_revision = NEW.marketing_consent_revision,
           confirmed_at = now()
     WHERE profile_id = NEW.id;
  END IF;
  RETURN NEW;
END;
$function$;

