CREATE OR REPLACE FUNCTION public.claim_audience_sync_jobs(
  p_batch_size integer DEFAULT 10,
  p_lease_seconds integer DEFAULT 600
)
RETURNS SETOF public.audience_sync_outbox
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_limit integer := least(greatest(coalesce(p_batch_size, 10), 1), 10);
  v_lease integer := least(greatest(coalesce(p_lease_seconds, 600), 300), 3600);
BEGIN
  RETURN QUERY
  WITH chosen AS (
    SELECT id FROM public.audience_sync_outbox
    WHERE (status = 'pending' AND available_at <= now())
       OR (status = 'processing' AND claimed_at < now() - make_interval(secs => v_lease))
    ORDER BY available_at, id
    LIMIT v_limit
    FOR UPDATE SKIP LOCKED
  )
  UPDATE public.audience_sync_outbox o
     SET status = 'processing', attempts = o.attempts + 1,
         claimed_at = now(), updated_at = now()
    FROM chosen c WHERE o.id = c.id
  RETURNING o.*;
END;
$function$;

CREATE OR REPLACE FUNCTION public.complete_audience_sync_job(
  p_id bigint,
  p_revision bigint,
  p_outcome text,
  p_confirmed boolean DEFAULT false,
  p_error text DEFAULT NULL
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_attempts integer;
  v_current_revision bigint;
  v_status text;
BEGIN
  IF p_outcome NOT IN ('succeeded', 'retryable', 'terminal') THEN
    RAISE EXCEPTION 'invalid audience sync outcome' USING ERRCODE = '22023';
  END IF;
  SELECT revision, status, attempts
    INTO v_current_revision, v_status, v_attempts
    FROM public.audience_sync_outbox
   WHERE id = p_id FOR UPDATE;
  IF NOT FOUND THEN RETURN false; END IF;
  IF v_current_revision IS DISTINCT FROM p_revision THEN
    UPDATE public.audience_sync_outbox
       SET status = 'pending', attempts = 0, available_at = now(),
           claimed_at = NULL, delivered_at = NULL,
           terminal_at = NULL, purge_after = NULL,
           last_error = format('reconcile after stale provider completion revision %s', p_revision),
           updated_at = now()
     WHERE id = p_id;
    RETURN false;
  END IF;
  IF v_status <> 'processing' THEN RETURN false; END IF;
  UPDATE public.audience_sync_outbox
     SET status = CASE WHEN p_outcome = 'succeeded' AND p_confirmed THEN 'delivered'
                       WHEN p_outcome = 'terminal' THEN 'failed' ELSE 'pending' END,
         available_at = CASE WHEN p_outcome = 'retryable'
                             THEN now() + make_interval(secs => least(3600, greatest(30, 30 * (2 ^ least(v_attempts, 7)))))
                             ELSE now() END,
         claimed_at = NULL,
         delivered_at = CASE WHEN p_outcome = 'succeeded' AND p_confirmed THEN now() ELSE NULL END,
         terminal_at = CASE
           WHEN (p_outcome = 'succeeded' AND p_confirmed) OR p_outcome = 'terminal' THEN now()
           ELSE NULL END,
         purge_after = CASE
           WHEN (p_outcome = 'succeeded' AND p_confirmed) OR p_outcome = 'terminal'
             THEN now() + interval '30 days'
           ELSE NULL END,
         last_error = CASE WHEN p_outcome = 'succeeded' AND p_confirmed THEN NULL ELSE p_error END,
         updated_at = now()
   WHERE id = p_id AND revision = p_revision AND status = 'processing';
  RETURN FOUND;
END;
$function$;

-- G0 remediation: metadata mutation stays BEFORE the profile write, while all
-- child-table evidence and queue work runs AFTER the parent row exists.
CREATE OR REPLACE FUNCTION public.profile_consent_metadata_guard()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $function$
DECLARE
  v_email text := public.audience_normalize_email(NEW.email);
  v_changed boolean;
  v_hard_suppressed boolean := false;
BEGIN
  IF v_email IS NOT NULL THEN
    SELECT EXISTS (
      SELECT 1 FROM public.audience_suppression_events
       WHERE email_hash = encode(digest(v_email, 'sha256'), 'hex')
         AND event_type IN ('email.bounced', 'email.complained', 'email.suppressed')
    ) INTO v_hard_suppressed;
  END IF;

  IF TG_OP = 'INSERT' THEN
    v_changed := true;
  ELSE
    v_changed := OLD.email IS DISTINCT FROM NEW.email
      OR OLD.marketing_opt_in IS DISTINCT FROM NEW.marketing_opt_in;
  END IF;

  IF NOT v_changed THEN
    NEW.marketing_opt_in_source := OLD.marketing_opt_in_source;
    NEW.marketing_opt_in_at := OLD.marketing_opt_in_at;
    NEW.marketing_consent_revision := OLD.marketing_consent_revision;
    RETURN NEW;
  END IF;

  IF v_hard_suppressed AND coalesce(NEW.marketing_opt_in, false) THEN
    NEW.marketing_opt_in := false;
    NEW.marketing_opt_in_source := 'provider_hard_suppression';
  ELSIF TG_OP = 'INSERT' THEN
    NEW.marketing_opt_in_source := 'profile_insert';
  ELSE
    NEW.marketing_opt_in_source := 'profile_change';
  END IF;
  NEW.marketing_opt_in_at := now();
  NEW.marketing_consent_revision := CASE
    WHEN TG_OP = 'INSERT' THEN 1
    ELSE OLD.marketing_consent_revision + 1
  END;
  RETURN NEW;
END;
$function$;

